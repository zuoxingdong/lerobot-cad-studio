#!/usr/bin/env python3
"""Pack assets/ into src/data/packed.js (the data module) and src/data/assets_manifest.json.

    nice -n 10 python3 tools/build/pack_assets.py

Robots, parts and scenes go in as their own documents; the browser resolves a composition
(core/package.js) and computes every transform (core/robot-model.js).  Each drawable mesh is
decimated per connected body, instanced by content, gzipped and base64'd; a part's plate
gets the rigid `print_transform` fitted from its mesh.  Thumbnails are the committed PNGs.
The page reads the data through src/data/assets.js.
Needs numpy, trimesh and vtk (the decimator).  Budget: 4 MB of mesh data.
"""
import base64
import fnmatch
import gc
import gzip
import json
import os
import struct
import sys
import warnings

import numpy as np

from packlib.atomic import write_json, write_text
from packlib.common import ASSETS, BUDGET_MB, OUT_JS, OUT_JSON, QUANT, STUDIO, log
from packlib.decimate import _file_md5, load_dec
from packlib.printfit import fit_print

warnings.filterwarnings('ignore')

# face caps by component id, first match wins
FACE_CAPS = [
    ('4-Omni-Directional-Wheel*', 30000), ('base_plate_layer*', 15000), ('Base_08q*', 8000),
    ('SO_ARM100_08k_Mirror*', 8000), ('Wrist_Roll_Pitch*', 8000), ('Moving_Jaw*', 8000),
    ('ST3215_Servo_Motor*', 6000), ('STS3215*', 6000), ('Camera-Model*', 6000),
    ('Top_Plate', 9000), ('Bottom_Plate', 9000), ('Tip_Support', 4000), ('Distal_Shell', 4000),
    ('Internal_Rod', 3000), ('*', 5000),
]
# this project's parts, by the component id they resolve to
PART_CAPS = [('pi_case_cradle', 9000), ('pi_case_panel', 7000), ('*', 8000)]

JS_HEADER = '''// src/data/packed.js - GENERATED by tools/build/pack_assets.py from assets/, do NOT edit.
// %(summary)s
//
// ROBOTS[<id>] = { manifest, meshes, thumbnail }   manifest = assets/robots/<id>/robot.json,
//               every component's `mesh` rewritten to its mesh id (rps/robot@2 is unresolved);
//               a `kind: "attachment"` package is here for the robot that attaches it, and
//               robotIds() (src/data/assets.js, the API) leaves it out
// PARTS[<id>]  = { part, meshes }                  part = assets/parts/<id>/part.json plus the
//               fitted print_transform / print_bbox_mm / print_fit_rmse_mm of each plate
// SCENES[<id>] = { scene }
// meshes: { <meshId>: { stl_gz, faces } | { mesh_ref: "<owner>:<meshId>", faces } }; an owner
// is a robot id or "part:<id>"; stl_gz = base64(gzip(binary STL, mm, facet normals zeroed)).
// thumbnail: base64 PNG, the committed assets/robots/<id>/thumb.png.

'''


def cap_for(cid, table):
    for pat, v in table:
        if fnmatch.fnmatchcase(cid, pat):
            return v
    return 5000


def to_bin_stl(m):
    v = np.round(np.asarray(m.vertices, dtype=np.float64) * QUANT) / QUANT
    f = np.asarray(m.faces, dtype=np.int64)
    n = len(f)
    tri = np.ascontiguousarray(v[f].astype('<f4')).reshape(n, 9)
    blk = np.zeros((n, 50), dtype=np.uint8)
    blk[:, 12:48] = tri.view(np.uint8)
    used = v[f].reshape(-1, 3)
    return b'\x00' * 80 + struct.pack('<I', n) + blk.tobytes(), used.min(0), used.max(0)


class Packer:
    """Meshes of every owner, instanced by (content, cap) across the whole bundle."""

    def __init__(self):
        self.meshes = {}         # owner -> {mesh id -> entry}
        self.info = {}           # owner -> {mesh id -> packing numbers}
        self.seen = {}           # (md5, cap) -> "owner:mesh"

    def add(self, owner, mid, path, cap):
        mt = self.meshes.setdefault(owner, {})
        inf = self.info.setdefault(owner, {})
        key = (_file_md5(path), int(cap))
        if key in self.seen:
            ref = self.seen[key]
            o, _, m = ref.rpartition(':')
            mt[mid] = {'mesh_ref': ref, 'faces': self.meshes[o][m]['faces']}
            inf[mid] = dict(self.info[o][m], mesh_ref=ref, b64_bytes=0, stl_bytes=0)
            return
        m = load_dec(path, cap)
        data, lo, hi = to_bin_stl(m)
        b64 = base64.b64encode(gzip.compress(data, 9, mtime=0)).decode('ascii')
        mt[mid] = {'stl_gz': b64, 'faces': int(len(m.faces))}
        inf[mid] = dict(faces=int(len(m.faces)), stl_bytes=len(data), b64_bytes=len(b64),
                        source=os.path.relpath(path, STUDIO), cap=int(cap), mesh_ref=None,
                        bounds=[[round(float(x), 4) for x in lo], [round(float(x), 4) for x in hi]])
        self.seen[key] = '%s:%s' % (owner, mid)
        del m
        gc.collect()

    def bytes(self, owner):
        return sum(len(v.get('stl_gz', '')) for v in self.meshes.get(owner, {}).values())


def _docs(kind, name):
    root = os.path.join(ASSETS, kind)
    out = {}
    for d in sorted(os.listdir(root)):
        p = os.path.join(root, d, name)
        if not d.startswith('_') and os.path.isfile(p):
            out[d] = (os.path.join(root, d), json.load(open(p, encoding='utf-8')))
    return out


def pack_robot(pk, rid, d, doc):
    """A robot@1 package: one mesh per component, keyed by component id."""
    for c in doc.get('components', []):
        pk.add(rid, c['id'], os.path.join(d, c['mesh']), cap_for(c.get('part') or c['id'], FACE_CAPS))
        c['mesh'] = c['id']
    for sp in doc.get('spares', []):
        pk.add(rid, sp['id'], os.path.join(d, sp['mesh']), 5000)
        sp['mesh'] = sp['id']
    return doc


def pack_part(pk, pid, d, doc):
    """A part: its drawable meshes, and the bed pose of every plate it ships."""
    owner = 'part:' + pid
    for m in doc['meshes']:
        if m.get('file'):
            cid = m.get('component') or '%s_%s' % (pid, m['id'])
            pk.add(owner, m['id'], os.path.join(d, m['file']), cap_for(cid, PART_CAPS))
        pr = m.get('print')
        if m.get('file') and pr and not pr.startswith('part:'):
            fit = fit_print(os.path.join(d, m['file']), os.path.join(d, pr))
            if fit:
                m.update(fit)
            else:
                m['print_fit_note'] = 'the plate is not a rigid image of the mesh, so no bed pose is stated'
    pk.meshes.setdefault(owner, {})
    return doc


def main():
    pk = Packer()
    robots, parts, scenes = {}, {}, {}
    # plain packages first, compositions after: the home page's order
    docs = sorted(_docs('robots', 'robot.json').items(), key=lambda kv: kv[1][1].get('schema') == 'rps/robot@2')
    for rid, (d, doc) in docs:
        log('== robot %s' % rid)
        robots[rid] = pack_robot(pk, rid, d, doc) if doc.get('schema') == 'rps/robot@1' else doc
        pk.meshes.setdefault(rid, {})
    for pid, (d, doc) in _docs('parts', 'part.json').items():
        log('== part %s' % pid)
        parts[pid] = pack_part(pk, pid, d, doc)
    for sid, (d, doc) in _docs('scenes', 'scene.json').items():
        scenes[sid] = doc
    thumbs = {}
    for rid in robots:
        p = os.path.join(ASSETS, 'robots', rid, robots[rid].get('thumbnail') or 'thumb.png')
        thumbs[rid] = base64.b64encode(open(p, 'rb').read()).decode('ascii') if os.path.isfile(p) else None

    owners = list(pk.meshes)
    mesh_b = sum(pk.bytes(o) for o in owners)
    total = mesh_b + sum(len(t or '') for t in thumbs.values())
    stored = sum(1 for o in owners for v in pk.meshes[o].values() if 'stl_gz' in v)
    attach = [rid for rid, doc in robots.items() if doc.get('kind') == 'attachment']
    attached = {a['robot'] for doc in robots.values() for a in doc.get('attach', [])}
    orphans = [rid for rid in attach if rid not in attached]
    if orphans:
        log('!! attachment package(s) no robot attaches: %s' % ', '.join(orphans))
        return 1
    summary = ('%d robots + %d attachment, %d parts / %d meshes stored / %.2f MB base64 (budget %.1f MB)'
               % (len(robots) - len(attach), len(attach), len(parts), stored, total / 1e6, BUDGET_MB))
    R = {rid: {'manifest': doc, 'meshes': pk.meshes[rid], 'thumbnail': thumbs[rid]}
         for rid, doc in robots.items()}
    P = {pid: {'part': doc, 'meshes': pk.meshes['part:' + pid]} for pid, doc in parts.items()}
    S = {sid: {'scene': doc} for sid, doc in scenes.items()}
    js = (JS_HEADER % {'summary': summary}
          + 'export const ROBOTS = ' + json.dumps(R, separators=(',', ':')) + ';\n'
          + 'export const PARTS = ' + json.dumps(P, separators=(',', ':')) + ';\n'
          + 'export const SCENES = ' + json.dumps(S, separators=(',', ':')) + ';\n')
    write_text(OUT_JS, js)
    man = {'robots': {rid: {'manifest': doc, 'meshes': pk.info.get(rid, {}), 'bytes_b64': pk.bytes(rid),
                            'thumbnail_bytes': len(thumbs[rid] or '')} for rid, doc in robots.items()},
           'parts': {pid: {'part': doc, 'meshes': pk.info.get('part:' + pid, {}),
                           'bytes_b64': pk.bytes('part:' + pid)} for pid, doc in parts.items()},
           'scenes': sorted(scenes),
           '_summary': dict(robots=len(robots) - len(attach), attachments=attach, parts=len(parts), total_b64_bytes=total,
                            budget_bytes=int(BUDGET_MB * 1e6), over_budget=bool(total > BUDGET_MB * 1e6),
                            js_bytes=os.path.getsize(OUT_JS))}
    write_json(OUT_JSON, man)
    log('\n' + summary)
    for o in owners:
        log('  %-26s %7.0f kB  %3d meshes' % (o, pk.bytes(o) / 1024, len(pk.meshes[o])))
    log('wrote %s (%.2f MB) and %s' % (os.path.relpath(OUT_JS, STUDIO), os.path.getsize(OUT_JS) / 1e6,
                                       os.path.relpath(OUT_JSON, STUDIO)))
    if total > BUDGET_MB * 1e6:
        log('!! OVER the %.1f MB budget' % BUDGET_MB)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
